const DICTS: Record<Lang, Dict> = { en, "zh-Hans": zhHans, "zh-Hant": zhHant };

export type MsgKey = keyof typeof en;

export function t(lang: Lang, key: MsgKey | string, vars: Record<string, string | number> = {}): string {
  const dict = DICTS[lang] as Record<string, string>;
  const template = dict[key] ?? (en as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export const LANG_LABELS: Record<Lang, string> = { en: "EN", "zh-Hans": "简", "zh-Hant": "繁" };

export function detectUiLang(): Lang {
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return /tw|hk|mo|hant/.test(nav) ? "zh-Hant" : "zh-Hans";
  return "en";
}

export function locale(lang: Lang): string {
  return lang === "en" ? "en-GB" : lang === "zh-Hans" ? "zh-CN" : "zh-HK";
}
